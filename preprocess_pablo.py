df_clean = df_clean[df_clean['owners_midpoint'] <= 5000000].copy()

# Identificar si el juego es gratuito (Free to Play)
df_clean['is_free'] = (df_clean['price'] == 0).astype(int)

# ─────────────────────────────────────────────────────────────────────────────
# 3. Cálculo Target: Succes Score (0-100)
# ─────────────────────────────────────────────────────────────────────────────
