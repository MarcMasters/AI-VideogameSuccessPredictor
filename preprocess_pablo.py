# Contamos el volumen de lanzamientos por distribuidora
pub_counts = df_clean["publisher_clean"].value_counts()

# Filtramos solo los que tengan un histórico sólido (mínimo 3 juegos en el dataset)
valid_publishers = pub_counts[pub_counts >= 3].index

# Calculamos el éxito base inicial de la comunidad para mapear los publishers
# Usamos una métrica temporal de rendimiento (ventas + jugadores) para darles el peso inicial
df_clean['temp_perf'] = (df_clean['owners_midpoint'] * 0.6) + (df_clean['peak_ccu'] * 0.4)
pub_means = df_clean[df_clean["publisher_clean"].isin(valid_publishers)].groupby("publisher_clean")['temp_perf'].mean()

# Escalamos el peso de los publishers robustos de 0 a 100
p_min, p_max = pub_means.min(), pub_means.max()
pub_means_scaled = ((pub_means - p_min) / (p_max - p_min + 1e-9)) * 100
publisher_weight_map = pub_means_scaled.to_dict()

# Mapeamos los pesos al dataset principal. Los de < 3 juegos se quedan con 0
df_clean["publisher_weight"] = df_clean["publisher_clean"].map(publisher_weight_map).fillna(0)

# ─────────────────────────────────────────────────────────────────────────────
# 4. Lógica de pesos en publishers (mínimo 3 juegos y de 0-100)
# ─────────────────────────────────────────────────────────────────────────────
# Nota híbrida de calidad: Si Metacritic es 0, usamos las reseñas de los usuarios
df_clean['quality_score'] = df_clean.apply(
    lambda x: (x['metacritic_score'] + x['pct_pos_total']) / 2 if x['metacritic_score'] > 0 else x['pct_pos_total'],
    axis=1
)

# Definimos las columnas del éxito final
